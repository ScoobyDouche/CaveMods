using Microsoft.Extensions.Logging;
using Mutagen.Bethesda.Plugins;

using NexusMods.Abstractions.Loadouts;
using NexusMods.Abstractions.Loadouts.Sorting;
using NexusMods.Abstractions.Loadouts.Synchronizers;
using NexusMods.Abstractions.Loadouts.Synchronizers.Rules;
using NexusMods.Games.CreationEngine.Abstractions;
using NexusMods.Hashing.xxHash3;
using NexusMods.MnemonicDB.Abstractions;
using NexusMods.Paths;
using NexusMods.Sdk.FileStore;
using NexusMods.Sdk.Games;
using NexusMods.Sdk.Loadouts;

namespace NexusMods.Games.CreationEngine;

public class PluginsFile : IIntrinsicFile
{
    private readonly ICreationEngineGame _game;
    private readonly ISorter _sorter;
    private readonly ILogger<PluginsFile> _logger;

    private record struct Metadata(GamePath GamePath, RelativePath FileName, ModKey ModKey, Hash Hash, PluginHeader Header);

    public PluginsFile(ILogger<PluginsFile> logger, ICreationEngineGame game, ISorter sorter)
    {
        _game = game;
        _sorter = sorter;
        Path = game.PluginsFile;
        _logger = logger;
    }
    
    public GamePath Path { get; }
    
    public async Task Write(Stream stream, Loadout.ReadOnly loadout, Dictionary<GamePath, SyncNode> syncTree)
    {
        var plugins = await syncTree
            .Where(p => p.Key.Parent == KnownPaths.Data && KnownCEExtensions.PluginFiles.Contains(p.Key.Extension))
            .Where(p => p.Value.HaveLoadout)
            .ToAsyncEnumerable()
            .SelectAwait(MakeMetadata)
            .ToDictionaryAsync(x => x.ModKey);

        if (plugins.Count == 0)
            return;
        
        var officialPlugins = _game.OfficialPlugins;
        var sorted = _sorter.Sort(plugins.Values.ToList(), IdSelector, plugin => RuleCreator(plugin, plugins, officialPlugins))
            .ToList();
        _logger.LogDebug("Sorted {Count} plugin files", sorted.Count);

        var format = _game.PluginListFormat;
        await using var sw = new StreamWriter(stream, leaveOpen: true);
        await sw.WriteLineAsync("# Generated by CaveMods");

        foreach (var plugin in sorted)
        {
            var line = format == PluginListFormat.Asterisk ? $"*{plugin.FileName}" : plugin.FileName.ToString();
            await sw.WriteLineAsync(line);
        }

        await sw.FlushAsync();

        if (format == PluginListFormat.TimestampOrdered)
            ApplyTimestampLoadOrder(loadout, sorted);
    }

    /// <summary>
    /// Base time for timestamp-ordered load orders. Every plugin gets a time one minute after the
    /// previous one, so the oldest plugin (the base game master) loads first.
    /// </summary>
    internal static readonly DateTime TimestampLoadOrderBase = new(2008, 10, 28, 0, 0, 0, DateTimeKind.Utc);

    /// <summary>
    /// Fallout 3 and New Vegas ignore the order of the plugins file and load plugins oldest first,
    /// so set each plugin's modification time to match the sorted load order.
    /// </summary>
    /// <remarks>
    /// This runs after mod files are extracted, as intrinsic files are written last during a synchronize.
    /// </remarks>
    private void ApplyTimestampLoadOrder(Loadout.ReadOnly loadout, IReadOnlyList<Metadata> sorted)
    {
        var locations = loadout.InstallationInstance.Locations;
        for (var i = 0; i < sorted.Count; i++)
        {
            var path = locations.ToAbsolutePath(sorted[i].GamePath);
            if (!path.FileExists)
            {
                _logger.LogWarning("Can't set load order time on {Plugin}, file doesn't exist on disk", sorted[i].FileName);
                continue;
            }

            var time = TimestampLoadOrderBase.AddMinutes(i);
            try
            {
                if (path.FileInfo.LastWriteTimeUtc != time)
                    File.SetLastWriteTimeUtc(path.ToNativeSeparators(OSInformation.Shared), time);
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "Failed to set load order time on {Plugin}", sorted[i].FileName);
            }
        }
    }

    private static IReadOnlyList<ISortRule<Metadata, ModKey>> RuleCreator(Metadata metadata, Dictionary<ModKey, Metadata> allPlugins, ModKey[] officialPlugins)
    {
        var resultList = new List<ISortRule<Metadata, ModKey>>();
        foreach (var master in metadata.Header.Masters)
        {
            // Skip missing masters here, we'll catch that in diagnostics
            if (!allPlugins.ContainsKey(master))
                continue;
            
            resultList.Add(new After<Metadata, ModKey>()
            {
                Other = master,
            });
        }

        // Official plugins load first, in their fixed order
        if (officialPlugins.Length > 0)
        {
            var officialIndex = Array.IndexOf(officialPlugins, metadata.ModKey);
            if (officialIndex >= 0)
            {
                // After the closest earlier official plugin that is present
                for (var i = officialIndex - 1; i >= 0; i--)
                {
                    if (!allPlugins.ContainsKey(officialPlugins[i])) continue;
                    resultList.Add(new After<Metadata, ModKey>() { Other = officialPlugins[i] });
                    break;
                }
            }
            else
            {
                foreach (var official in officialPlugins)
                {
                    if (!allPlugins.ContainsKey(official)) continue;
                    resultList.Add(new After<Metadata, ModKey>() { Other = official });
                }
            }
        }

        // ESLs should come after ESMs
        if (metadata.FileName.Extension == KnownCEExtensions.ESL)
        {
            foreach (var other in allPlugins.Values)
            {
                if (other.FileName.Extension == KnownCEExtensions.ESM)
                    resultList.Add(new After<Metadata, ModKey>()
                    {
                        Other = other.ModKey,
                    });
            }
        }
        
        // ESPs should come after ESMs and ESLs
        if (metadata.FileName.Extension == KnownCEExtensions.ESP)
        {
            foreach (var other in allPlugins.Values)
            {
                if (other.FileName.Extension == KnownCEExtensions.ESM || other.FileName.Extension == KnownCEExtensions.ESL)
                    resultList.Add(new After<Metadata, ModKey>()
                    {
                        Other = other.ModKey,
                    });
            }
        }
        
        return resultList;
    }

    private static ModKey IdSelector(Metadata metadata)
    {
        return metadata.ModKey;
    }

    private async ValueTask<Metadata> MakeMetadata(KeyValuePair<GamePath, SyncNode> arg)
    {
        var relPath = arg.Key.Path.FileName;
        Hash hash;
        
        // We need to figure out if we should look at the loadout or the disk
        var syncNode = arg.Value;
        if (syncNode.Actions.HasFlag(Actions.ExtractToDisk) || syncNode.Disk.Hash == Hash.Zero || syncNode.SourceItemType == LoadoutSourceItemType.Game)
            hash = syncNode.Loadout.Hash;
        else
            hash = syncNode.Disk.Hash;
        
        // An unreadable header shouldn't break writing the plugins file, sort it without masters instead
        var modHeader = await _game.ParsePlugin(hash, relPath)
                        ?? new PluginHeader(ModKey.FromFileName(relPath.ToString()), []);
        return new Metadata(arg.Key, relPath, modHeader.ModKey, hash, modHeader);
    }
    


    public Task Ingest(Stream stream, Loadout.ReadOnly loadout, Dictionary<GamePath, SyncNode> syncTree, ITransaction tx)
    {
        // TODO: Implement once we have sorting
        return Task.CompletedTask;
    }
}
